/** The opening view for a phone region code, or null for a missing, unknown or non-country code. */
export function getCountryView(regionCode: string | null | undefined): MapRegion | null {
  if (!regionCode) return null;
  const view = COUNTRY_VIEWS[regionCode.toUpperCase()];
  if (!view) return null;
  const [latitude, longitude, latitudeDelta, longitudeDelta] = view;
  const region = { latitude, longitude, latitudeDelta, longitudeDelta };
  return isValidRegion(region) ? region : null;
}
